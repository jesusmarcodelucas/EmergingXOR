exc(c,I2,Li2,color=C_EXC); exc(c,P2,Lp2,color=C_EXC)
exc(c,I2,H2,color=C_IN); exc(c,P2,H2,color=C_IN)
inh(c,H2,Li2,divide=True); inh(c,H2,Lp2,divide=True)
exc(c,Li2,R,color=C_EXC,rb=0.62); exc(c,Lp2,R,color=C_EXC,rb=0.62)
c.text(3.55,6.6,"\u2212",ha="center",va="center",color=C_INH,fontsize=17,weight="bold")
c.text(6.45,6.6,"\u2212",ha="center",va="center",color=C_INH,fontsize=17,weight="bold")
