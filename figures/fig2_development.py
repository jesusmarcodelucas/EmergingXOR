b.text(5,1.4,"$E_{Cl}$ falls; GABA\nflips  +  \u2192  \u2212 .",ha="center",fontsize=8.1,color="#333")
# C governor (simplified: hub now shunts laterals -> read-out; no F+/F-, no equations)
c=fig.add_subplot(gs[0,2]); c.set_xlim(0,10); c.set_ylim(0,10); c.axis("off")
c.text(5,9.5,"C  Governor",ha="center",fontsize=11,weight="bold")
I2=node(c,(2.3,8.4),"I",C_IN); P2=node(c,(7.7,8.4),"P",C_IN)
Li2=node(c,(2.3,5.0),"L$_i$",C_LAT); Lp2=node(c,(7.7,5.0),"L$_p$",C_LAT)
