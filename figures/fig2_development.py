H=node(a,(5.0,6.4),"INH",C_DEP,r=0.5)
exc(a,I,H,color=C_IN); exc(a,P,H,color=C_IN)
exc(a,H,Li,color=C_DEP); exc(a,H,Lp,color=C_DEP)
exc(a,I,Li,color=C_EXC,ls=(0,(2.5,2.5))); exc(a,P,Lp,color=C_EXC,ls=(0,(2.5,2.5)))
a.text(5,9.5,"A  Builder",ha="center",fontsize=11,weight="bold")
a.text(3.7,6.4,"+",ha="center",va="center",color=C_DEP,fontsize=17,weight="bold")
a.text(6.3,6.4,"+",ha="center",va="center",color=C_DEP,fontsize=17,weight="bold")
a.text(5,2.3,"Depolarising GABA (+): the hub co-activates\nthe laterals; GDP-like bursts grow the\nexcitatory arms (dashed).",ha="center",fontsize=8.1,color="#333")
# B switch
b=fig.add_subplot(gs[0,1]); b.set_xlim(0,10); b.set_ylim(0,10); b.axis("off")
b.text(5,9.5,"B  The switch",ha="center",fontsize=11,weight="bold")
b.plot([5,5],[2.6,7.6],color="#ccc",lw=9,solid_capstyle="round",zorder=1)
b.plot([3.9,6.1],[5.0,5.0],color="#777",lw=1,ls=":"); b.text(6.25,5.0,"V$_{thr}$",fontsize=8,color="#777",va="center")
b.add_patch(Circle((5,6.9),0.30,fc=C_DEP,ec="k",zorder=3)); b.text(2.7,6.9,"E$_{Cl}$ high\ndepol (+)",fontsize=8,color=C_DEP,va="center",ha="center")
b.add_patch(Circle((5,3.1),0.30,fc=C_INH,ec="k",zorder=3)); b.text(2.7,3.1,"E$_{Cl}$ low\nshunt (\u2212)",fontsize=8,color=C_INH,va="center",ha="center")
b.annotate("",xy=(5,3.9),xytext=(5,6.1),arrowprops=dict(arrowstyle="-|>",color=C_EXC,lw=2.6,mutation_scale=18),zorder=4)
